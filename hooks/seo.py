def on_page_markdown(markdown, page, config, files):
    src = page.file.src_uri
    page.meta.setdefault("description", DESCRIPTIONS.get(src, config["site_description"]))
    if src == "index.md":
        version = re.search(r'^version = "([^"]+)"', (Path(config["docs_dir"]).parent / "pyproject.toml")
                            .read_text(encoding="utf-8"), re.M)
        app = {**APP, "url": config["site_url"], "softwareVersion": version.group(1) if version else None}
        page.meta["jsonld"] = json.dumps(app)
    elif src == "faq.md":
        qa = re.findall(r"^## (.+?)\n\n(.+?)(?=\n## |\Z)", markdown, re.S | re.M)
        page.meta["jsonld"] = json.dumps({"@context": "https://schema.org", "@type": "FAQPage", "mainEntity": [
            {"@type": "Question", "name": q.strip(),
             "acceptedAnswer": {"@type": "Answer", "text": re.sub(r"\s+", " ", a).strip()}} for q, a in qa]})
    page.meta["jsonld"] = page.meta.get("jsonld", "").replace("</", "<\\/")
    return markdown


def on_post_build(config):
    site, docs, url = Path(config["site_dir"]), Path(config["docs_dir"]), config["site_url"]
    (site / "robots.txt").write_text(
        "# Everyone, including AI crawlers (GPTBot, ClaudeBot, PerplexityBot, Google-Extended), is welcome.\n"
        f"User-agent: *\nAllow: /\n\nSitemap: {url}sitemap.xml\n", encoding="utf-8")
    pages = [(p.file.src_uri, p.title) for p in _pages(config["nav"])]
    root = docs.parent
    llms = (root / "llms.txt").read_text(encoding="utf-8").rstrip() + "\n\n## Docs\n\n" + "".join(
        f"- [{t}]({url}{_url(s)}): {DESCRIPTIONS.get(s, '')}\n" for s, t in pages) + \
        f"\nFull text of every page: {url}llms-full.txt\n"
    (site / "llms.txt").write_text(llms, encoding="utf-8")
    full = [f"# keelyard documentation (full text)\n\nSource: {REPO} · Docs: {url}\n"]
    for s, _ in pages:
        full.append(f"\n\n---\n\nURL: {url}{_url(s)}\n\n" + (docs / s).read_text(encoding="utf-8"))
    (site / "llms-full.txt").write_text("".join(full), encoding="utf-8")


def on_nav(nav, config, files):
    config["nav"] = nav
    return nav


def _pages(nav):
    return list(nav.pages)


def _url(src: str) -> str:
    return "" if src == "index.md" else src[:-3].removesuffix("/index") + "/"
